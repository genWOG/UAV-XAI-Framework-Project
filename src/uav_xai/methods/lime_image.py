import time
from typing import Any, Callable

import numpy as np
import torch
from skimage.segmentation import slic
from lime import lime_image
from skimage.segmentation import mark_boundaries
from sklearn.metrics import pairwise_distances

from ..core.base import Explainer
from ..core.target import XAITarget
from ..core.result import ExplanationResult


class LimeImageExplainer(Explainer):
    """
    LIME explainer for image classification.

    The explainer operates on an RGB numpy image and uses a
    user-provided preprocessing function to convert perturbed
    images into model input tensors.

    Parameters
    ----------
    preprocess:
        Callable converting one RGB image in HWC format to a
        PyTorch tensor with shape [C, H, W].
    num_samples:
        Number of perturbed samples generated by LIME.
    hide_color:
        Pixel color used when a superpixel is switched off.
    """

    def __init__(
        self,
        preprocess: Callable[[np.ndarray], torch.Tensor] | None,
        num_samples: int = 1000,
        hide_color: int | float | None = 0,
        segmentation_fn: Callable | None = None,
        target_iou_threshold: float = 0.5,
        num_segments: int = 100,
        compactness: float = 10.0,
        prediction_batch_size: int = 32,
        target_score_mode: str = "confidence_iou",
    ) -> None:

        if num_samples < 1:
            raise ValueError(
                "num_samples must be >= 1."
            )
        if not 0.0 <= target_iou_threshold <= 1.0:
            raise ValueError(
                "target_iou_threshold must be between 0 and 1."
            )
        if num_segments < 2:
            raise ValueError("num_segments must be >= 2.")
        if compactness <= 0:
            raise ValueError("compactness must be > 0.")
        if prediction_batch_size < 1:
            raise ValueError("prediction_batch_size must be >= 1.")
        if target_score_mode not in {"confidence_iou", "thresholded_confidence"}:
            raise ValueError("target_score_mode must be 'confidence_iou' or 'thresholded_confidence'.")

        self.preprocess = preprocess
        self.num_samples = num_samples
        self.hide_color = hide_color
        self.target_iou_threshold = target_iou_threshold
        self.num_segments = int(num_segments)
        self.compactness = float(compactness)
        self.prediction_batch_size = int(prediction_batch_size)
        self.target_score_mode = target_score_mode

        self._explainer = lime_image.LimeImageExplainer(
            random_state=42,
        )

        self._segmentation_fn = segmentation_fn

    def _validate_image(
        self,
        input_data: Any,
    ) -> np.ndarray:
        """
        Validate and normalize image input.

        Expected format:
            [H, W, 3]

        Accepted dtypes:
            uint8
            floating point
        """

        image = np.asarray(
            input_data
        )

        if image.ndim != 3:
            raise ValueError(
                "Image must have shape [H, W, 3]."
            )

        if image.shape[2] != 3:
            raise ValueError(
                "Only RGB images with 3 channels are supported."
            )

        if not np.isfinite(
            image.astype(np.float32)
        ).all():
            raise ValueError(
                "Image contains NaN or Inf values."
            )

        if image.dtype != np.uint8:

            image_min = float(
                image.min()
            )
            image_max = float(
                image.max()
            )

            if (
                image_min >= 0.0
                and image_max <= 1.0
            ):
                image = (
                    image * 255.0
                ).clip(
                    0,
                    255,
                )

            else:
                image = image.clip(
                    0,
                    255,
                )

            image = image.astype(
                np.uint8
            )

        return image

    def _build_predict_fn(
        self,
        model: Any,
    ) -> Callable[[np.ndarray], np.ndarray]:
        """
        Build LIME prediction callback.
        """

        if not callable(model):
            raise TypeError(
                "model must be callable."
            )

        def predict_fn(
            images: np.ndarray,
        ) -> np.ndarray:

            tensors = []

            for image in images:

                tensor = self.preprocess(
                    image
                )

                if not isinstance(
                    tensor,
                    torch.Tensor,
                ):
                    raise TypeError(
                        "preprocess must return "
                        "torch.Tensor."
                    )

                if tensor.ndim != 3:
                    raise ValueError(
                        "preprocess must return "
                        "tensor with shape [C, H, W]."
                    )

                tensors.append(
                    tensor
                )

            batch = torch.stack(
                tensors,
                dim=0,
            )

            try:
                device = next(
                    model.parameters()
                ).device

                batch = batch.to(
                    device
                )

            except (
                AttributeError,
                StopIteration,
            ):
                pass

            with torch.no_grad():
                output = model(
                    batch
                )

                if output.ndim != 2:
                    raise ValueError(
                        "Model output must have shape "
                        "[batch_size, num_classes]."
                    )

                probabilities = torch.softmax(
                    output,
                    dim=1,
                )

            return (
                probabilities
                .detach()
                .cpu()
                .numpy()
            )

        return predict_fn

    @staticmethod
    def _bbox_iou(
        box_a: list[float],
        box_b: list[float],
    ) -> float:
        ax1, ay1, ax2, ay2 = box_a
        bx1, by1, bx2, by2 = box_b

        ix1 = max(ax1, bx1)
        iy1 = max(ay1, by1)
        ix2 = min(ax2, bx2)
        iy2 = min(ay2, by2)

        intersection = (
            max(0.0, ix2 - ix1)
            * max(0.0, iy2 - iy1)
        )

        area_a = (
            max(0.0, ax2 - ax1)
            * max(0.0, ay2 - ay1)
        )
        area_b = (
            max(0.0, bx2 - bx1)
            * max(0.0, by2 - by1)
        )

        union = area_a + area_b - intersection
        return intersection / union if union > 0.0 else 0.0

    def _build_detection_predict_fn(
        self,
        model: Any,
        target: XAITarget,
    ) -> Callable[[np.ndarray], np.ndarray]:
        if not hasattr(model, "predict"):
            raise TypeError(
                "Detection LIME requires a model with predict()."
            )

        if target.bbox is None:
            raise ValueError(
                "Detection LIME requires target.bbox."
            )

        target_bbox = [
            float(value)
            for value in target.bbox
        ]

        from .yolo_fast_scorer import YoloDetectionScorer
        scorer = YoloDetectionScorer(
            model=model,
            target_bbox=target_bbox,
            target_class_id=target.class_id,
            score_mode=self.target_score_mode,
            iou_threshold=self.target_iou_threshold,
            confidence_threshold=0.001,
        )
        def predict_fn(images: np.ndarray) -> np.ndarray:
            rgb_images = [self._validate_image(image) for image in images]
            bgr_images = [image[:, :, ::-1].copy() for image in rgb_images]
            return scorer(bgr_images)

        predict_fn.scorer = scorer
        return predict_fn

    def _segment_detection(
        self,
        image: np.ndarray,
    ) -> np.ndarray:
        """Use spatially compact, reproducible superpixels for YOLO explanations."""
        return slic(
            image,
            n_segments=self.num_segments,
            compactness=self.compactness,
            start_label=0,
            channel_axis=-1,
        )

    def _explain_detection(
        self,
        model: Any,
        input_data: Any,
        target: XAITarget,
    ) -> ExplanationResult:
        start_time = time.perf_counter()

        image = self._validate_image(input_data)

        predict_fn = self._build_detection_predict_fn(
            model,
            target,
        )

        original_scores = predict_fn(
            np.expand_dims(image, axis=0)
        )

        lime_target = 1

        # Reproduce LIME's binary superpixel neighbourhood, but generate
        # perturbed images vectorially instead of looping over every segment
        # for every sample. The weighted local regression remains LIME's own.
        segmentation_fn = (
            self._segmentation_fn
            if self._segmentation_fn is not None
            else self._segment_detection
        )
        segments = np.asarray(segmentation_fn(image))
        if segments.shape != image.shape[:2]:
            raise ValueError(
                "segmentation_fn must return an array with shape [H, W]."
            )
        _, segments = np.unique(segments, return_inverse=True)
        segments = segments.reshape(image.shape[:2]).astype(np.int32, copy=False)
        n_segments = int(segments.max()) + 1

        # Match lime-image's fudged-image semantics.
        if self.hide_color is None:
            fudged_image = image.copy()
            for segment_id in range(n_segments):
                selected = segments == segment_id
                mean_color = image[selected].mean(axis=0)
                fudged_image[selected] = mean_color.astype(image.dtype)
        else:
            fudged_image = np.broadcast_to(
                np.asarray(self.hide_color), image.shape
            ).astype(image.dtype, copy=True)

        data = self._explainer.random_state.randint(
            0, 2, self.num_samples * n_segments
        ).reshape(self.num_samples, n_segments)
        data[0, :] = 1

        label_batches = []
        for batch_start in range(0, self.num_samples, self.prediction_batch_size):
            mask_batch = data[batch_start:batch_start + self.prediction_batch_size]
            visible_pixels = mask_batch[:, segments] > 0
            perturbed_batch = np.where(
                visible_pixels[..., np.newaxis],
                image[np.newaxis, ...],
                fudged_image[np.newaxis, ...],
            )
            label_batches.append(predict_fn(perturbed_batch))
        labels = np.concatenate(label_batches, axis=0)

        distances = pairwise_distances(
            data, data[0].reshape(1, -1), metric="cosine"
        ).ravel()
        _, local_exp, local_fit_score, local_prediction = (
            self._explainer.base.explain_instance_with_data(
                data,
                labels,
                distances,
                lime_target,
                n_segments,
                feature_selection=self._explainer.feature_selection,
            )
        )

        attribution = np.zeros(
            segments.shape,
            dtype=np.float32,
        )

        for segment_id, weight in local_exp:
            attribution[segments == segment_id] = weight

        confidence = float(
            original_scores[0, lime_target]
        )

        runtime_ms = (
            time.perf_counter() - start_time
        ) * 1000.0

        return ExplanationResult(
            method="lime",
            attribution=attribution,
            target=target.class_id,
            confidence=confidence,
            runtime_ms=runtime_ms,
            input_type="image",
            feature_names=None,
            metadata={
                "explainer": "lime_image_detection",
                "num_samples": self.num_samples,
                "num_segments": n_segments,
                "prediction_batch_size": self.prediction_batch_size,
                "local_fit_score": float(local_fit_score),
                "local_prediction": float(np.asarray(local_prediction).reshape(-1)[0]),
                "image_shape": list(image.shape),
                "target_task": "detection",
                "target_class_id": target.class_id,
                "detection_index": target.detection_index,
                "bbox": list(target.bbox),
                "target_iou_threshold": self.target_iou_threshold,
                "prediction_backend": predict_fn.scorer.backend,
                "fast_path_max_score_difference": predict_fn.scorer.max_score_difference,
                "target_score_mode": self.target_score_mode,
            },
        )

    def explain(
        self,
        model: Any,
        input_data: Any,
        target: int | str | None = None,
    ) -> ExplanationResult:

        if isinstance(target, XAITarget):
            if target.task != "detection":
                raise ValueError(
                    "LIME received an unsupported XAI target."
                )

            return self._explain_detection(
                model=model,
                input_data=input_data,
                target=target,
            )

        start_time = time.perf_counter()

        image = self._validate_image(
            input_data
        )

        predict_fn = self._build_predict_fn(
            model
        )

        # Determine target automatically if needed.
        original_probabilities = predict_fn(
            np.expand_dims(
                image,
                axis=0,
            )
        )

        if target is None:
            target = int(
                np.argmax(
                    original_probabilities[0]
                )
            )

        target = int(target)

        if not (
            0 <= target
            < original_probabilities.shape[1]
        ):
            raise ValueError(
                f"Target class {target} is out of range."
            )

        explanation = (
            self._explainer.explain_instance(
                image=image,
                classifier_fn=predict_fn,
                top_labels=None,
                labels=(
                    [target]
                ),
                hide_color=self.hide_color,
                num_samples=self.num_samples,
                segmentation_fn=self._segmentation_fn,
            )
        )

        # LIME returns a list of:
        # (superpixel_id, weight)
        local_exp = explanation.local_exp[
            target
        ]

        segments = (
            explanation.segments
        )

        attribution = np.zeros(
            segments.shape,
            dtype=np.float32,
        )

        for segment_id, weight in local_exp:
            attribution[
                segments == segment_id
            ] = weight

        confidence = float(
            original_probabilities[
                0,
                target,
            ]
        )

        runtime_ms = (
            time.perf_counter()
            - start_time
        ) * 1000.0

        return ExplanationResult(
            method="lime",
            attribution=attribution,
            target=target,
            confidence=confidence,
            runtime_ms=runtime_ms,
            input_type="image",
            feature_names=None,
            metadata={
                "num_samples": self.num_samples,
                "num_segments": int(
                    len(
                        np.unique(
                            segments
                        )
                    )
                ),
                "image_shape": list(
                    image.shape
                ),
                "explainer": "lime_image",
                "segments": segments,
            },
        )

    @staticmethod
    def visualize_segments(
        image: np.ndarray,
        segments: np.ndarray,
    ) -> np.ndarray:
        """
        Draw superpixel boundaries on an image.
        """

        image = np.asarray(
            image,
            dtype=np.float32,
        )

        if image.max() > 1.0:
            image = image / 255.0

        return mark_boundaries(
            image,
            segments,
        )
